create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  display_name text not null default 'Пользователь',
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, email, display_name)
  values (new.id, new.email, coalesce(new.raw_user_meta_data ->> 'display_name', split_part(new.email, '@', 1)))
  on conflict (id) do update set email = excluded.email, display_name = excluded.display_name;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create table if not exists public.listings (
  id bigint generated by default as identity primary key,
  seller_id uuid not null references public.profiles(id) on delete cascade,
  seller_name text not null default 'Продавец',
  title text not null check (char_length(title) between 2 and 120),
  category text not null default 'Другое',
  price numeric(12,2) not null check (price > 0),
  stock integer not null default 1 check (stock >= 0),
  image_url text,
  description text not null default '',
  rating numeric(2,1) not null default 0,
  reviews_count integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.conversations (
  id bigint generated by default as identity primary key,
  listing_id bigint not null references public.listings(id) on delete cascade,
  buyer_id uuid not null references public.profiles(id) on delete cascade,
  seller_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(listing_id, buyer_id),
  check (buyer_id <> seller_id)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.conversations(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 1000),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.listings enable row level security;
alter table public.conversations enable row level security;
alter table public.messages enable row level security;

drop policy if exists "Profiles visible to signed in users" on public.profiles;
create policy "Profiles visible to signed in users" on public.profiles for select to authenticated using (true);
drop policy if exists "Users update own profile" on public.profiles;
create policy "Users update own profile" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "Active listings are public" on public.listings;
create policy "Active listings are public" on public.listings for select to anon, authenticated using (is_active or seller_id = auth.uid());
drop policy if exists "Users create own listings" on public.listings;
create policy "Users create own listings" on public.listings for insert to authenticated with check (seller_id = auth.uid());
drop policy if exists "Users update own listings" on public.listings;
create policy "Users update own listings" on public.listings for update to authenticated using (seller_id = auth.uid()) with check (seller_id = auth.uid());
drop policy if exists "Users delete own listings" on public.listings;
create policy "Users delete own listings" on public.listings for delete to authenticated using (seller_id = auth.uid());


drop policy if exists "Buyer can update own conversation" on public.conversations;
create policy "Buyer can update own conversation" on public.conversations for update to authenticated using (buyer_id = auth.uid()) with check (buyer_id = auth.uid());

drop policy if exists "Participants see conversations" on public.conversations;
create policy "Participants see conversations" on public.conversations for select to authenticated using (buyer_id = auth.uid() or seller_id = auth.uid());
drop policy if exists "Buyers create conversations for active listings" on public.conversations;
create policy "Buyers create conversations for active listings" on public.conversations for insert to authenticated with check (buyer_id = auth.uid() and exists (select 1 from public.listings l where l.id = listing_id and l.seller_id = seller_id and l.is_active));

drop policy if exists "Participants read messages" on public.messages;
create policy "Participants read messages" on public.messages for select to authenticated using (exists (select 1 from public.conversations c where c.id = conversation_id and (c.buyer_id = auth.uid() or c.seller_id = auth.uid())));
drop policy if exists "Participants send messages as themselves" on public.messages;
create policy "Participants send messages as themselves" on public.messages for insert to authenticated with check (sender_id = auth.uid() and exists (select 1 from public.conversations c where c.id = conversation_id and (c.buyer_id = auth.uid() or c.seller_id = auth.uid())));

create index if not exists listings_active_created_idx on public.listings(is_active, created_at desc);
create index if not exists messages_conversation_created_idx on public.messages(conversation_id, created_at);
